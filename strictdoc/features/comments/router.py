"""
Routes of the comments: add, edit, delete, resolve, reopen, and a screen that
lists the comments of the project.

The routes are only reachable when the COMMENTS project feature is activated
(412 otherwise). The role each route needs is in
strictdoc/features/roles/route_roles.py. The author and the date of a comment
come from the server (the principal), never from the browser.
"""

from typing import List, Optional, Tuple

from fastapi import APIRouter, Depends, Form, HTTPException, Request
from fastapi.responses import HTMLResponse
from markupsafe import Markup
from starlette.responses import Response

from strictdoc.backend.sdoc.models.document import SDocDocument
from strictdoc.backend.sdoc.models.node import SDocNode
from strictdoc.core.document_iterator import SDocDocumentIterator
from strictdoc.export.html.document_type import DocumentType
from strictdoc.export.html.renderers.link_renderer import LinkRenderer
from strictdoc.export.html.renderers.markup_renderer import MarkupRenderer
from strictdoc.features.comments.model import (
    STATUS_OPEN,
    STATUS_RESOLVED,
    Comment,
    now_iso,
)
from strictdoc.features.comments.service import (
    comments_of,
    find_comment,
    save_comments,
    supports_comments,
)
from strictdoc.features.reviewers.reviewers import can_comment
from strictdoc.features.roles.principal import Principal
from strictdoc.features.roles.roles import ROLE_AUTHOR, role_allows
from strictdoc.features.roles.router import get_principal
from strictdoc.helpers.cast import assert_cast
from strictdoc.helpers.mid import MID
from strictdoc.server.project_context import ProjectContext

HTTP_STATUS_PRECONDITION_FAILED = 412


def create_comments_routers(
    *, context: ProjectContext
) -> Tuple[APIRouter, APIRouter]:
    """The routes that only read and the routes that change a node."""

    def require_feature() -> None:
        if not context.project_config.is_activated_comments():
            raise HTTPException(status_code=HTTP_STATUS_PRECONDITION_FAILED)

    read_router = APIRouter(dependencies=[Depends(require_feature)])
    write_router = APIRouter(dependencies=[Depends(require_feature)])

    def find_node(node_mid: str) -> SDocNode:
        node = context.export_action.traceability_index.get_node_by_mid_weak(
            MID(node_mid)
        )
        if not isinstance(node, SDocNode):
            raise HTTPException(status_code=404, detail="Node not found.")
        if not supports_comments(node):
            raise HTTPException(
                status_code=400,
                detail="This kind of node has no COMMENT field.",
            )
        if not context.export_action.traceability_index.can_comment_node(node):
            raise HTTPException(
                status_code=403,
                detail="Editing is disabled for autogenerated content.",
            )
        return node

    def require_commenter(principal: Principal, node: SDocNode) -> None:
        """Authors and reviewers of the project, and the reviewers of the document."""
        document = assert_cast(node.get_document(), SDocDocument)
        if not can_comment(principal.role, principal.user, document):
            raise HTTPException(
                status_code=403,
                detail="You are not a reviewer of this document.",
            )

    def panel(node: SDocNode, error: Optional[str] = None) -> Response:
        document = assert_cast(node.get_document(), SDocDocument)
        assert document.meta is not None
        renderer = MarkupRenderer.create(
            markup=document.config.get_markup(),
            traceability_index=context.export_action.traceability_index,
            link_renderer=LinkRenderer(
                root_path=document.meta.get_root_path_prefix(),
                static_path=context.project_config.dir_for_sdoc_assets,
            ),
            html_templates=context.html_generator.html_templates,
            config=context.project_config,
            context_document=document,
        )
        items = [
            {
                "comment": comment_,
                "html": renderer.render_node_field(
                    DocumentType.DOCUMENT, field_
                ),
            }
            for comment_, field_ in zip(
                comments_of(node), node.get_comment_fields()
            )
        ]
        output = context.env().render_template_as_markup(
            "features/comments/stream_panel.jinja.html",
            node_mid=node.reserved_mid.get_string_value(),
            items=items,
            interactive=True,
            error=error,
        )
        return HTMLResponse(
            content=output,
            status_code=200 if error is None else 422,
            headers={"Content-Type": "text/vnd.turbo-stream.html"},
        )

    def may_change(principal: Principal, comment: Comment) -> bool:
        """The author of a comment, and an author or administrator, may."""
        return role_allows(principal.role, ROLE_AUTHOR) or (
            len(comment.author) > 0 and comment.author == principal.user
        )

    def locate(node: SDocNode, comment_id: str) -> Tuple[List[Comment], int]:
        comments = comments_of(node)
        index = find_comment(comments, comment_id)
        if index is None:
            raise HTTPException(status_code=404, detail="Comment not found.")
        return comments, index

    @write_router.post("/actions/comments/add", response_class=Response)
    def add_comment(
        request: Request,
        node_mid: str = Form(...),
        body: str = Form(...),
        anchor: str = Form(""),
        anchor_n: int = Form(0),
    ) -> Response:
        principal = get_principal(request)
        node = find_node(node_mid)
        require_commenter(principal, node)
        if len(body.strip()) == 0:
            return panel(node, "A comment cannot be empty.")
        comments = comments_of(node)
        comments.append(
            Comment.new(principal.user, body, anchor=anchor, anchor_n=anchor_n)
        )
        return panel(node, save_comments(context, node, comments))

    @write_router.post("/actions/comments/edit", response_class=Response)
    def edit_comment(
        request: Request,
        node_mid: str = Form(...),
        comment_id: str = Form(...),
        body: str = Form(...),
    ) -> Response:
        principal = get_principal(request)
        node = find_node(node_mid)
        require_commenter(principal, node)
        comments, index = locate(node, comment_id)
        if not may_change(principal, comments[index]):
            raise HTTPException(
                status_code=403,
                detail="Only the author of a comment may change it.",
            )
        if len(body.strip()) == 0:
            return panel(node, "A comment cannot be empty.")
        comments[index].body = body.strip()
        comments[index].legacy = False
        return panel(node, save_comments(context, node, comments))

    @write_router.post("/actions/comments/delete", response_class=Response)
    def delete_comment(
        request: Request,
        node_mid: str = Form(...),
        comment_id: str = Form(...),
    ) -> Response:
        principal = get_principal(request)
        node = find_node(node_mid)
        require_commenter(principal, node)
        comments, index = locate(node, comment_id)
        if not may_change(principal, comments[index]):
            raise HTTPException(
                status_code=403,
                detail="Only the author of a comment may delete it.",
            )
        del comments[index]
        return panel(node, save_comments(context, node, comments))

    def set_status(
        node_mid: str, comment_id: str, status: str, principal: Principal
    ) -> Response:
        node = find_node(node_mid)
        comments, index = locate(node, comment_id)
        comment = comments[index]
        if comment.legacy:
            # The first change gives a legacy comment its header.
            comment.legacy = False
            comment.id = Comment.new("", "").id
        comment.status = status
        comment.resolved_by = (
            principal.user if status == STATUS_RESOLVED else ""
        )
        comment.resolved_on = now_iso() if status == STATUS_RESOLVED else ""
        return panel(node, save_comments(context, node, comments))

    @write_router.post("/actions/comments/resolve", response_class=Response)
    def resolve_comment(
        request: Request,
        node_mid: str = Form(...),
        comment_id: str = Form(...),
    ) -> Response:
        return set_status(
            node_mid, comment_id, STATUS_RESOLVED, get_principal(request)
        )

    @write_router.post("/actions/comments/reopen", response_class=Response)
    def reopen_comment(
        request: Request,
        node_mid: str = Form(...),
        comment_id: str = Form(...),
    ) -> Response:
        return set_status(
            node_mid, comment_id, STATUS_OPEN, get_principal(request)
        )

    @read_router.get("/comments", response_class=Response)
    def comments_screen(status: str = "open") -> Response:
        rows = []
        for document_ in (
            context.export_action.traceability_index.document_tree.document_list
        ):
            iterator = SDocDocumentIterator(
                document=document_, node_filter=None
            )
            for node_, _ in iterator.all_content(print_fragments=False):
                if not isinstance(node_, SDocNode):
                    continue
                for comment_ in comments_of(node_):
                    if status not in ("all", comment_.status):
                        continue
                    rows.append(
                        {
                            "document": document_.title,
                            "node_ref": node_.reserved_uid
                            or node_.reserved_mid.get_string_value(),
                            "node_label": node_.reserved_uid
                            or node_.reserved_title
                            or node_.reserved_mid.get_string_value(),
                            "comment": comment_,
                        }
                    )
        output = Markup(
            context.env()
            .get_template("features/comments/screen.jinja.html")
            .render(rows=rows, selected_status=status)
        )
        return HTMLResponse(content=output, status_code=200)

    return read_router, write_router
